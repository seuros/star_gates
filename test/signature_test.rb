# frozen_string_literal: true

require 'test_helper'
require 'rbs'
require 'star_gates/adapters/redis_adapter'
require 'star_gates/telemetry/prometheus_adapter'
require 'star_gates/telemetry/opentelemetry_adapter'
require 'star_gates/jsonrpc_rails_adapter'

# Every public method the gem defines has a signature in sig/.
class SignatureTest < Minitest::Test
  LIB = File.expand_path('../lib', __dir__)
  SIG = File.expand_path('../sig', __dir__)

  def builder
    loader = RBS::EnvironmentLoader.new
    loader.add(path: Pathname(SIG))
    RBS::DefinitionBuilder.new(env: RBS::Environment.from_loader(loader).resolve_type_names)
  end

  def star_gates_modules
    Zeitwerk::Loader.eager_load_all
    ObjectSpace.each_object(Module).select do |mod|
      mod.name&.start_with?('StarGates') && Object.const_source_location(mod.name)&.first&.start_with?(LIB)
    end
  end

  # Public methods owned by `mod` and written in lib/ (not generated by a
  # dependency such as class_attribute or state_machines).
  def own_methods(mod)
    mod.public_instance_methods(false).select do |name|
      location = mod.instance_method(name).source_location
      location&.first&.start_with?(LIB)
    end
  end

  def test_every_public_method_has_a_signature
    definitions = builder
    missing = star_gates_modules.flat_map do |mod|
      type_name = RBS::TypeName.parse("::#{mod.name}")
      instance = definitions.build_instance(type_name).methods.keys
      singleton = definitions.build_singleton(type_name).methods.keys
      (own_methods(mod) - instance).map { |name| "#{mod}##{name}" } +
        (own_methods(mod.singleton_class) - singleton).map { |name| "#{mod}.#{name}" }
    end

    assert_empty missing.sort
  end

  def test_signatures_validate
    assert(system(Gem.ruby, '-S', 'rbs', '-I', SIG, 'validate', out: File::NULL, err: File::NULL))
  end
end
